export function getMockIdeaAnalytics(id) {
  const found = MOCK_EXPLORE_IDEAS.find((item) => String(item.id) === String(id));
  if (!found) return null;
  const milestones = found.milestones || [];
  const completed = milestones.filter((m) => m.status === 'completed').length;
  const inProgress = milestones.filter((m) => m.status === 'in_progress').length;
  const todo = milestones.filter((m) => m.status === 'todo').length;
  const rate = milestones.length > 0 ? Math.round((completed / milestones.length) * 100) : 75;
  return {
    views: found.views || 250,
    votes: found.votes || 42,
    followers: Math.round((found.votes || 30) * 0.65),
    currentVersion: found.current_version,
    totalVersions: (found.versions || []).length,
    versions: (found.versions || []).length,
    contributors: found.contributors || 3,
    comments: found.comment_count || 5,
    suggestions: {
      total: 4,
      accepted: Math.max(1, found.current_version - 1),
      pending: 1,
      declined: 0,
      rejected: 0,
      rate: 80,
    },
    milestones: {
      total: milestones.length || 3,
      completed: completed || 2,
      inProgress: inProgress || 1,
      todo: todo || 0,
      rate,
    },
    roadmap: {
      total: milestones.length || 3,
      completed: completed || 2,
      progress: rate,
    },
  };
}
